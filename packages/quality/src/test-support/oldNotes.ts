const CONTRACT = {
	content: [
		'import { Schema } from "effect";',
		'import { Model } from "effect/schema";',
		'import { collection } from "@shivaedev/changes/keys.ts";',
		'import { contract } from "@shivaedev/contract/contract.ts";',
		'import { command, query } from "@shivaedev/contract/operation.ts";',
		'import { signedIn } from "@shivaedev/contract/readPolicy.ts";',
		'import { fieldRejection } from "@shivaedev/contract/rejection.ts";',
		'import { Conflict, InternalServerError, NotFound, ServiceUnavailable, TooManyRequests } from "@shivaedev/errors/taxonomy.ts";',
		'import { AuthenticatedUser } from "@shivaedev/identity/middleware.ts";',
		"",
		"export const noteFields = {",
		"\tid: Model.Field({ json: Schema.Number, select: Schema.Number, update: Schema.Number }),",
		'\ttitle: Schema.Trim.check(Schema.isNonEmpty({ message: "Enter a title" })),',
		"\tversion: Model.Field({ json: Schema.Number, select: Schema.Number, update: Schema.Number }),",
		"\twordCount: Schema.NullOr(Schema.Number),",
		"};",
		'export class Note extends Model.Class<Note>("Note")(noteFields) {}',
		"export const NoteFields = Schema.Struct({ title: Note.fields.title });",
		"export const NoteEditFields = Schema.Struct({ title: Note.fields.title, version: Note.fields.version });",
		"const NoteId = Schema.Struct({ id: Schema.Number });",
		"const NoteVersion = Schema.Struct({ ...NoteId.fields, version: Note.fields.version });",
		'export const notes = collection("notes", Schema.Number, { userId: Schema.String });',
		'const Get = query("get", {',
		"\tpayload: NoteId,",
		"\treadPolicy: signedIn,",
		"\trejections: { InternalServerError, NotFound, ServiceUnavailable },",
		"\tsuccess: Note.json,",
		"});",
		'const List = query("list", {',
		"\treadPolicy: signedIn,",
		"\trejections: { InternalServerError, ServiceUnavailable },",
		"\tsuccess: Schema.Array(Note.json),",
		"});",
		'export const Create = command("create", {',
		"\tinvalidates: () => [],",
		"\tpayload: NoteFields,",
		"\trejections: { Conflict, InternalServerError, Invalid: fieldRejection(NoteFields), ServiceUnavailable, TooManyRequests },",
		"\tsuccess: Note.json,",
		"});",
		'export const Import = command("import", {',
		"\tinvalidates: () => [],",
		"\tpayload: NoteId,",
		"\trejections: { Conflict, InternalServerError, Invalid: fieldRejection(NoteFields), NotFound, ServiceUnavailable, TooManyRequests },",
		"\tsuccess: Note.json,",
		"});",
		'export const Update = command("update", {',
		"\tinvalidates: () => [],",
		"\tpayload: Schema.Struct({ ...NoteId.fields, ...NoteEditFields.fields }),",
		"\trejections: { Conflict, InternalServerError, Invalid: fieldRejection(NoteEditFields), NotFound, ServiceUnavailable },",
		"\tsuccess: Note.json,",
		"});",
		'export const Delete = command("delete", {',
		"\tinvalidates: () => [],",
		"\tpayload: NoteVersion,",
		"\trejections: { Conflict, InternalServerError, NotFound, ServiceUnavailable },",
		"\tsuccess: Schema.Void,",
		"});",
		'export const Notes = contract("notes", { commands: [Create, Import, Update, Delete], queries: [List, Get] }).middleware(AuthenticatedUser);',
	]
		.join("\n")
		.concat("\n"),
	path: "src/modules/notes/notes.ts",
};

const CREATE = {
	content: [
		'import { Effect } from "effect";',
		'import { SessionUser } from "@shivaedev/identity/identity.ts";',
		'import { rateLimit } from "@shivaedev/rate-limit/rateLimit.ts";',
		'import { transact } from "@shivaedev/sql/transact.ts";',
		'import type { Create } from "#modules/notes/notes.ts";',
		'import { enqueueNote } from "#modules/notes/server/enqueue.ts";',
		'import { NotesRepository } from "#modules/notes/server/Repository.ts";',
		'import { notesSqlFailure } from "#modules/notes/server/sqlFailure.ts";',
		"",
		'export const createNote = Effect.fn("Notes.createNote")(function* ({ title }: typeof Create.payload.Type) {',
		"\tconst repository = yield* NotesRepository;",
		"\tconst { id: userId } = yield* SessionUser;",
		`\tyield* rateLimit({ key: \`notes.create:\${userId}\`, per: 10, window: "1 minute" });`,
		"\treturn yield* repository.insert({ title, userId, wordCount: null }).pipe(",
		"\t\tEffect.tap((row) => enqueueNote(row.id)),",
		"\t\ttransact({ onSqlError: notesSqlFailure }),",
		"\t);",
		"});",
	]
		.join("\n")
		.concat("\n"),
	path: "src/modules/notes/server/create.ts",
};

