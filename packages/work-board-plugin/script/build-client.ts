import { mkdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { Effect } from "effect";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = new URL("../src/adapters/generated/", import.meta.url);
const program = Effect.gen(function* () {
	const result = yield* Effect.promise(() =>
		build({
			absWorkingDir: root,
			banner: { js: "// Generated by pnpm build:client. Edit src/ and rebuild." },
			bundle: true,
			chunkNames: "shared",
			conditions: ["source"],
			entryPoints: { platformClient: "src/adapters/platformClient.ts", register: "src/register.tsx" },
			external: ["claude-code"],
			format: "esm",
			legalComments: "none",
			minify: true,
			outdir: fileURLToPath(output),
			platform: "node",
			sourcemap: false,
			splitting: true,
			target: "node24",
			write: false,
		}),
	);
	for (const file of result.outputFiles) {
		if (file.text.includes(root)) {
			return yield* Effect.die("The plugin bundle contains a local path.");
		}
	}
	yield* Effect.promise(() => rm(output, { force: true, recursive: true }));
	yield* Effect.promise(() => mkdir(output, { recursive: true }));
	for (const file of result.outputFiles) {
		yield* Effect.promise(() => writeFile(file.path, file.contents));
	}
});
Effect.runPromise(program);
