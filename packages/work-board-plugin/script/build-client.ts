import { mkdir, rm, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import { Effect } from "effect";
import { type BuildOptions, build } from "esbuild";
import { hostRefusals } from "#adapters/hostLoader.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = new URL("../src/adapters/generated/", import.meta.url);
const common: BuildOptions = {
	absWorkingDir: root,
	banner: { js: "// Generated by pnpm build:client. Edit src/ and rebuild." },
	bundle: true,
	conditions: ["source"],
	external: ["claude-code"],
	format: "esm",
	legalComments: "none",
	outdir: fileURLToPath(output),
	platform: "node",
	sourcemap: false,
	target: "node24",
	write: false,
};
const CLIENT = "#adapters/platformClient.ts";
const program = Effect.gen(function* () {
	// The host reads the hooks entry's source before running it, so that entry keeps its names as written and imports
	// the minified Effect client from a file beside it, kept under the size the host reads.
	const [bundled, hooks] = yield* Effect.promise(() =>
		Promise.all([
			build({ ...common, entryPoints: { platformClient: "src/adapters/platformClient.ts" }, minify: true }),
			build({ ...common, entryPoints: { register: "src/register.tsx" }, external: [...(common.external ?? []), CLIENT] }),
		]),
	);
	const files = [...bundled.outputFiles, ...hooks.outputFiles].map((file) => ({
		name: basename(file.path),
		path: file.path,
		text: file.text.replaceAll(`"${CLIENT}"`, '"./platformClient.js"'),
	}));
	if (files.some((file) => file.text.includes(root))) {
		return yield* Effect.die("The plugin bundle contains a local path.");
	}
	const refusals = hostRefusals("register.js", files);
	if (refusals.length > 0) {
		return yield* Effect.die(`The Claude Code host would refuse the plugin bundle:\n${refusals.join("\n")}`);
	}
	yield* Effect.promise(() => rm(output, { force: true, recursive: true }));
	yield* Effect.promise(() => mkdir(output, { recursive: true }));
	for (const file of files) {
		yield* Effect.promise(() => writeFile(file.path, file.text));
	}
});
Effect.runPromise(program);
