import { expect } from "@effect/vitest";
import { pending, released, workspace } from "#test/workspace.ts";

workspace.it("check explains how to restore a malformed manifest", [pending(), released], function* ({ write, cli }) {
	yield* write(".changeset/release.json", "{}");
	const result = yield* cli("check");
	expect(result.status).toBe(1);
	expect(result.stderr).toContain("restore the manifest generated by changesets apply");
});

workspace.it("check rejects an invalid release date", [pending(), released], function* ({ edit, cli }) {
	yield* edit(".changeset/release.json", (text) => text.replace(/"date": "[^"]+"/u, '"date": "2026-02-30"'));
	const result = yield* cli("check");
	expect(result.status).toBe(1);
	expect(result.stderr).toContain("valid UTC YYYY-MM-DD release date");
});

workspace.it("check rejects removing a package's released history", [], function* ({ remove, cli }) {
	yield* remove("packages/core/package.json");
	const result = yield* cli("check");
	expect(result.status).toBe(1);
	expect(result.stderr).toContain("restore the package and its released history");
});
