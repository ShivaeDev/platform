import { Effect } from "effect";
import { collectChangelog } from "#collectChangelog.ts";
import type { ChangesetConfig } from "#config.ts";
import { attempt, requireThat } from "#error.ts";
import type { Source, Workspace } from "#model.ts";
import { computePlan } from "#planner.ts";
import { readHistory } from "#readHistory.ts";
import { isChangeset, readWorkspace } from "#workspace.ts";

function same(left: unknown, right: unknown): boolean {
	return JSON.stringify(left) === JSON.stringify(right);
}

function validateInputs(before: readonly Source[], pending: readonly Source[], consumed: readonly Source[]): void {
	requireThat(
		new Set(consumed.map((source) => source.name)).size === consumed.length && consumed.every((source) => isChangeset(source.name)),
		"Release manifest changeset names must be unique .md filenames; restore the manifest generated by changesets apply.",
	);
	for (const source of consumed) {
		requireThat(
			!pending.some((item) => item.name === source.name),
			`${source.name}: consumed changesets must be deleted; remove .changeset/${source.name}.`,
		);
		const previous = before.find((item) => item.name === source.name);
		requireThat(
			previous === undefined || previous.text === source.text,
			`${source.name}: release inputs changed; restore the original changeset text and rerun changesets apply.`,
		);
	}
	for (const source of before) {
		const preserved = [...pending, ...consumed].find((item) => item.name === source.name);
		requireThat(
			preserved?.text === source.text,
			`${source.name}: keep pending changesets unchanged or consume them unchanged in .changeset/release.json; add a new file for later changes.`,
		);
	}
}

export function validateDiff(before: Workspace, after: Workspace): void {
	for (const old of before.packages) {
		requireThat(
			after.packages.some((pkg) => pkg.manifest.name === old.manifest.name),
			`${old.manifest.name}: restore the package and its released history before checking releases.`,
		);
	}
	const bumped = after.packages.filter((pkg) => {
		const old = before.packages.find((candidate) => candidate.manifest.name === pkg.manifest.name);
		const firstRelease = after.release?.plan.releases.find((candidate) => candidate.name === pkg.manifest.name);
		return old === undefined
			? firstRelease !== undefined && firstRelease.from !== pkg.manifest.version
			: old.manifest.version !== pkg.manifest.version;
	});
	if (bumped.length === 0) {
		requireThat(same(before.release, after.release), ".changeset/release.json changes only with a release; restore it and run changesets apply.");
		validateInputs(before.changesets, after.changesets, []);
		for (const pkg of after.packages) {
			const old = before.packages.find((candidate) => candidate.manifest.name === pkg.manifest.name);
			requireThat(
				old === undefined || old.changelog === pkg.changelog,
				`${pkg.manifest.name}: CHANGELOG.md changes require a version bump; add .changeset/<name>.md and run changesets apply.`,
			);
		}
		return;
	}
	const manifest = after.release;
	requireThat(
		manifest !== undefined && !same(before.release, manifest),
		"A release needs .changeset/release.json; restore versions and run changesets apply.",
	);
	if (manifest === undefined) {
		return;
	}
	validateInputs(before.changesets, after.changesets, manifest.plan.changesets);
	const packages = after.packages.map((pkg) => {
		const old = before.packages.find((candidate) => candidate.manifest.name === pkg.manifest.name);
		const version =
			old?.manifest.version ?? manifest.plan.releases.find((candidate) => candidate.name === pkg.manifest.name)?.from ?? pkg.manifest.version;
		return { ...pkg, manifest: { ...pkg.manifest, version } };
	});
	const plan = computePlan(packages, manifest.plan.changesets);
	requireThat(
		plan.releases.length > 0 && same(plan, manifest.plan),
		"Release manifest does not match the changeset plan; restore versions and rerun changesets apply, including published dependents.",
	);
	for (const pkg of after.packages) {
		const old = before.packages.find((candidate) => candidate.manifest.name === pkg.manifest.name);
		const release = plan.releases.find((candidate) => candidate.name === pkg.manifest.name);
		requireThat(
			pkg.manifest.version === (release?.to ?? old?.manifest.version ?? pkg.manifest.version),
			`${pkg.manifest.name}: version differs from the release plan; restore versions and rerun changesets apply.`,
		);
		const expected =
			release === undefined ? (old?.changelog ?? pkg.changelog) : collectChangelog(old?.changelog ?? "# Changelog\n", release, plan, manifest.date);
		requireThat(
			pkg.changelog === expected,
			`${pkg.manifest.name}: release notes differ from changesets apply; restore released history and regenerate the release from unchanged inputs.`,
		);
	}
}

export const checkRepository = Effect.fn("Changesets.checkRepository")(function* (root: string, config: ChangesetConfig = {}, reference?: string) {
	const after = yield* readWorkspace(root, config);
	yield* attempt(() => computePlan(after.packages, after.changesets));
	const before = yield* readHistory(root, config, reference);
	yield* attempt(() => validateDiff(before, after));
});
