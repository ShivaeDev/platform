import { sessionStatus } from "#engine/sessionStatus.ts";
import { views } from "#engine/views.ts";
import type { FleetRecord, FleetView } from "#model.ts";

export const STATUS_MARKER = "<!-- Generated by Work Fleet. -->";

function text(value: string): string {
	return value.replaceAll(/\s+/gu, " ").replaceAll(/[\\`*_[\]<>#!|]/gu, "\\$&");
}

function card(item: typeof FleetView.Type): string {
	const task = `/_board/item/${encodeURIComponent(item.workId)}`;
	const links = item.links.flatMap((link) => {
		if (!URL.canParse(link)) {
			return [];
		}
		const url = new URL(link);
		return ["http:", "https:"].includes(url.protocol) ? [`[PR](<${url.href.replaceAll("<", "%3C").replaceAll(">", "%3E")}>)`] : [];
	});
	const progress = item.sessions.filter((session) => session.lastProgressAt !== undefined).map((session) => text(sessionStatus(session)));
	return `### ${text(item.workId)}\n\n[Task](<${task}>)${links.map((link) => ` · ${link}`).join("")}\n\nStage: ${text(item.stage)}${item.recovery ? `\n\n${text(item.recovery)}` : ""}${item.blocker ? `\n\n${text(item.blocker)}` : ""}${progress.length === 0 ? "" : `\n\n${progress.join("\n\n")}`}`;
}

export function statusMarkdown(records: readonly FleetRecord[]): string {
	const current = views([...records].sort((left, right) => left.workId.localeCompare(right.workId)));
	return `${[
		STATUS_MARKER,
		"# Fleet status",
		"Generated from Fleet execution records. Task status remains authored in the task source.",
		...(
			[
				["Active", current.active],
				["Waiting on maintainer", current.waiting.maintainer],
				["Waiting on orchestrator", current.waiting.orchestrator],
				["Waiting on automation", current.waiting.automation],
				["Done", current.completed],
			] as const
		).flatMap(([heading, items]) => [`## ${heading}`, ...items.map(card)]),
	].join("\n\n")}\n`;
}
