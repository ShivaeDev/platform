import type { ImportRef } from "#code.ts";
import { importNames } from "#importNames.ts";

export interface PlannedList {
	// What the list holds, for its first line; it never reads as a module's source, so no run takes the file for an orphan.
	readonly holds: string;
	readonly items: readonly ImportRef[];
	readonly name: string;
}

export function emitList({ holds, items, name }: PlannedList): string {
	const names = importNames(items, new Set([name]));
	const listed = items.length === 0 ? "[]" : `[\n${items.map((item) => `\t${names.local(item)},\n`).join("")}]`;
	return [
		`// Generated by @shivaedev/build: ${holds}. Do not edit or commit this file; run \`pnpm generate\` to write it again.\n`,
		...names.lines.map((line) => `${line}\n`),
		`\nexport const ${name} = ${listed} as const;\n`,
	].join("");
}
