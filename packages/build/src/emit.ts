import { type Code, code, type ImportRef, joined } from "#code.ts";
import { importNames } from "#importNames.ts";

export interface PlannedOperation {
	readonly kind: "command" | "query";
	readonly members: readonly Code[];
	readonly name: string;
	readonly payload: Code | undefined;
	readonly rejections: readonly (readonly [string, ImportRef])[];
	readonly success: Code;
}

export interface PlannedModule {
	readonly exportName: string;
	readonly keyScope: Code | undefined;
	readonly middleware: Code | undefined;
	readonly module: ImportRef;
	readonly name: string;
	readonly operations: readonly PlannedOperation[];
	readonly source: string;
	readonly subject: Code | undefined;
}

const CLIENT_CONTRACT: ImportRef = {
	name: "clientContract",
	preferred: "clientContract",
	specifier: "@shivaedev/contract/clientContract.ts",
	typeOnly: false,
};
const MATCHES: ImportRef = {
	name: "ClientMatchesModule",
	preferred: "ClientMatchesModule",
	specifier: "@shivaedev/contract/clientMatchesModule.ts",
	typeOnly: true,
};
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/u;
const HEADER = /^\/\/ Generated by @shivaedev\/build from (?<source>.+)\. Do not edit or commit this file; run `pnpm generate` to write it again\.$/u;

function headerOf(source: string): string {
	return `// Generated by @shivaedev/build from ${source}. Do not edit or commit this file; run \`pnpm generate\` to write it again.`;
}

// The module a file was generated from, read from its first line, so generate tells its own files from others under src/generated.
export function generatedFrom(text: string): string | undefined {
	return HEADER.exec(text.split("\n", 1)[0] ?? "")?.groups?.source;
}

function keyOf(name: string): string {
	return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

export function identifierOf(name: string): string {
	const words = name.split(/[^A-Za-z0-9_$]+/u).filter((word) => word !== "");
	const camel = words.map((word, index) => (index === 0 ? word : `${word.charAt(0).toUpperCase()}${word.slice(1)}`)).join("");
	return /^[0-9]/u.test(camel) || camel === "" ? `_${camel}` : camel;
}

function entries(lines: readonly Code[]): Code {
	return code("{\n", ...lines.map((line) => code("\t\t", line, ",\n")), "\t}");
}

function field(name: string, value: Code | undefined): readonly Code[] {
	return value === undefined ? [] : [code(`\t${name}: `, value, ",\n")];
}

export function emit(planned: PlannedModule): string {
	const operations = planned.operations;
	const base = identifierOf(planned.name);
	const wireName = `${base}Wire`;
	const matchName = `${base}MatchModule`;
	const moduleType = { ...planned.module, preferred: `${planned.exportName}Module` };
	function client(kind: PlannedOperation["kind"]) {
		const chosen = operations.filter((operation) => operation.kind === kind);
		return chosen.length === 0
			? undefined
			: entries(
					chosen.map((operation) =>
						operation.members.length === 0
							? code(`${keyOf(operation.name)}: {}`)
							: code(`${keyOf(operation.name)}: { `, joined(operation.members, ", "), " }"),
					),
				);
	}
	const payloads = operations.flatMap((operation) =>
		operation.payload === undefined ? [] : [code(`${keyOf(operation.name)}: `, operation.payload)],
	);
	const contract = code(
		...field("commands", client("command")),
		...field("keyScope", planned.keyScope),
		...field("middleware", planned.middleware),
		`\tname: ${JSON.stringify(planned.name)},\n`,
		...field("payloads", payloads.length === 0 ? undefined : entries(payloads)),
		...field("queries", client("query")),
		...field("subject", planned.subject),
		`\twire: ${wireName},\n`,
	);
	const all = code(
		contract,
		CLIENT_CONTRACT,
		MATCHES,
		moduleType,
		...operations.flatMap((operation) => [operation.success, ...operation.rejections.map(([, ref]) => ref)]),
	);
	const names = importNames(all, new Set([wireName, matchName, planned.exportName]));
	const wire = operations.map((operation) => {
		const rejections = operation.rejections.map(([tag, ref]) => (names.local(ref) === tag ? tag : `${keyOf(tag)}: ${names.local(ref)}`));
		const listed = rejections.length === 0 ? "{}" : `{ ${rejections.join(", ")} }`;
		return `\t${keyOf(operation.name)}: { rejections: ${listed}, success: ${names.text(operation.success)} },\n`;
	});
	return [
		`${headerOf(planned.source)}\n`,
		...names.lines.map((line) => `${line}\n`),
		`\nexport const ${wireName} = {\n${wire.join("")}} as const;\n`,
		`\nexport const ${planned.exportName} = ${names.local(CLIENT_CONTRACT)}({\n${names.text(contract)}});\n`,
		`\nexport const ${matchName}: ${names.local(MATCHES)}<typeof ${planned.exportName}, typeof ${names.local(moduleType)}> = true;\n`,
	].join("");
}
