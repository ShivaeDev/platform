import { expect } from "vitest";
import { cookieApp } from "#test-support/cookieApp.ts";

cookieApp.it("sign-up and sign-in keep their cookie sessions against the PostgreSQL host", [], function* ({ signUp, signIn, signOut, session }) {
	expect((yield* signUp()).error).toBeNull();
	const signedUp = yield* session();
	expect(signedUp.response.ok).toBe(true);
	expect(signedUp.response.status).toBe(200);
	expect(signedUp.response.headers.get("content-type")).toContain("application/json");
	expect(signedUp.response.headers.get("set-cookie")).toBeNull();
	expect(signedUp.result.error).toBeNull();
	expect(signedUp.session).toMatchObject({ user: { email: "alice@app.test" } });
	expect(signedUp.result.data).toMatchObject({ user: { email: "alice@app.test" } });
	expect(yield* signOut()).toBe(200);
	const signedOut = yield* session();
	expect(signedOut.response.ok).toBe(true);
	expect(signedOut.response.status).toBe(200);
	expect(signedOut.response.headers.get("content-type")).toContain("application/json");
	expect(signedOut.response.headers.get("set-cookie")).toBeNull();
	expect(signedOut.result.error).toBeNull();
	expect(signedOut.session).toBeNull();
	expect(signedOut.result.data).toBeNull();
	expect((yield* signIn()).error).toBeNull();
	const signedIn = yield* session();
	expect(signedIn.response.ok).toBe(true);
	expect(signedIn.response.status).toBe(200);
	expect(signedIn.response.headers.get("content-type")).toContain("application/json");
	expect(signedIn.response.headers.get("set-cookie")).toBeNull();
	expect(signedIn.result.error).toBeNull();
	expect(signedIn.session).toMatchObject({ user: { email: "alice@app.test" } });
	expect(signedIn.result.data).toMatchObject({ user: { email: "alice@app.test" } });
	expect(yield* signOut()).toBe(200);
	const revoked = yield* session();
	expect(revoked.response.ok).toBe(true);
	expect(revoked.response.status).toBe(200);
	expect(revoked.response.headers.get("content-type")).toContain("application/json");
	expect(revoked.response.headers.get("set-cookie")).toBeNull();
	expect(revoked.result.error).toBeNull();
	expect(revoked.session).toBeNull();
	expect(revoked.result.data).toBeNull();
});
